"""Deterministic synthetic inputs and the LZFSE test vectors made from them by the pinned reference encoder.

    lzfse_vectors.py --regenerate   build tools/ios/lzfse_ref_encode.c with cc, encode every input below and write tests/fixtures/lzfse_vectors.json

The inputs are generated here (a fixed 64-bit LCG, no Apple data, no random module), so the test regenerates the raw bytes
itself and compares them with the decoder's output for the fixture's encoded bytes. The fixture records which block kinds
each encoded stream contains, taken from tools/ios/lzfse_py.iter_blocks while generating; a test asserts the same list."""
import hashlib
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / "tests/fixtures/lzfse_vectors.json"
WORDS = ["kernel", "launchd", "dyld", "shared", "cache", "mach", "port", "bootstrap", "service", "framework",
         "springboard", "backboardd", "iokit", "display", "buffer", "stride", "surface", "memory", "thread", "queue"]


class Lcg:
    def __init__(self, seed):
        self.x = seed & 0xFFFFFFFFFFFFFFFF

    def next(self):
        self.x = (self.x * 6364136223846793005 + 1442695040888963407) & 0xFFFFFFFFFFFFFFFF
        return self.x >> 33

    def below(self, n):
        return self.next() % n


def text(n, seed):
    r = Lcg(seed)
    out = bytearray()
    while len(out) < n:
        out += WORDS[r.below(len(WORDS))].encode() + (b" " if r.below(7) else b"\n")
    return bytes(out[:n])


def runs(n, seed):
    """Long single-byte runs and short repeated patterns: small match distances that overlap their own output."""
    r = Lcg(seed)
    out = bytearray()
    while len(out) < n:
        kind = r.below(3)
        if kind == 0:
            out += bytes([r.below(256)]) * (3 + r.below(200))
        elif kind == 1:
            pat = bytes(r.below(256) for _ in range(2 + r.below(5)))
            out += pat * (2 + r.below(60))
        else:
            out += bytes(r.below(256) for _ in range(1 + r.below(30)))
    return bytes(out[:n])


def noise(n, seed):
    r = Lcg(seed)
    return bytes(r.next() & 0xFF for _ in range(n))


def mixed(n, seed):
    """Text, runs and noise in alternating chunks, so matches reach back across several encoder blocks."""
    r = Lcg(seed)
    out = bytearray()
    chunks = []
    while len(out) < n:
        k = r.below(4)
        size = 500 + r.below(6000)
        if k == 0:
            piece = text(size, r.next())
        elif k == 1:
            piece = runs(size, r.next())
        elif k == 2:
            piece = noise(size // 4, r.next())
        else:
            piece = bytes(chunks[r.below(len(chunks))]) if chunks else text(size, r.next())
        chunks.append(piece)
        out += piece
    return bytes(out[:n])


INPUTS = {
    "lzvn-text": lambda: text(3000, 1),
    "lzvn-runs": lambda: runs(3500, 2),
    "lzfse-text": lambda: text(30000, 3),
    "lzfse-runs": lambda: runs(60000, 4),
    "lzfse-multi-block": lambda: mixed(400000, 5),
    "raw-noise": lambda: noise(6000, 6),
}


def build_tools(workdir):
    ref = ROOT / "references/lzfse/src"
    out = Path(workdir) / "lzfse_ref_encode"
    srcs = [ROOT / "tools/ios/lzfse_ref_encode.c"] + [ref / n for n in (
        "lzfse_encode.c", "lzfse_encode_base.c", "lzvn_encode_base.c", "lzfse_decode.c", "lzfse_decode_base.c", "lzfse_fse.c", "lzvn_decode_base.c")]
    subprocess.run(["cc", "-O2", "-I" + str(ref), *map(str, srcs), "-o", str(out)], check=True)
    return out


def regenerate():
    sys.path.insert(0, str(ROOT / "tools/ios"))
    import lzfse_py
    entries = {}
    with tempfile.TemporaryDirectory() as tmp:
        enc = build_tools(tmp)
        for name, make in INPUTS.items():
            raw = make()
            src, dst = Path(tmp) / "in.bin", Path(tmp) / "out.lzfse"
            src.write_bytes(raw)
            subprocess.run([str(enc), str(src), str(dst)], check=True, capture_output=True)
            enc_bytes = dst.read_bytes()
            kinds = []
            for kind, _out in lzfse_py.iter_blocks(enc_bytes):
                kinds.append(kind)
            assert lzfse_py.decode(enc_bytes) == raw, name
            entries[name] = dict(raw_bytes=len(raw), raw_sha256=hashlib.sha256(raw).hexdigest(), encoded_hex=enc_bytes.hex(), block_kinds=kinds)
            print(name, len(raw), "->", len(enc_bytes), sorted(set(kinds)))
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(json.dumps(dict(
        encoder="https://github.com/lzfse/lzfse e634ca58b4821d9f3d560cdc6df5dec02ffc93fd (references/lzfse), lzfse_encode_buffer",
        inputs="generated by tools/ios/lzfse_vectors.py (synthetic, no Apple data)", vectors=entries), indent=1) + "\n")


if __name__ == "__main__":
    if sys.argv[1:] == ["--regenerate"]:
        regenerate()
    else:
        print(__doc__)
        sys.exit(2)
